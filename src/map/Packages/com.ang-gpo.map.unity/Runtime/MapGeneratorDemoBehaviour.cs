namespace Map.Unity
{
    /// <summary>
    /// Specifies the topology strategy used for one demo location group.
    /// </summary>
    public enum DemoLocationTopology
    {
        Linear,
        Branching,
        Loop,
        Hub
    }

    /// <summary>
    /// Defines one named location group generated by the Unity map demo.
    /// </summary>
    [Serializable]
    public sealed class DemoLocationTopologyDefinition
    {
        public string groupName = "Settlement";
        public DemoLocationTopology topology = DemoLocationTopology.Hub;
        [Min(1)] public int nodeCount = 7;
        [Min(2)] public int maxDegree = 3;
        [Min(1)] public int cycleCount = 1;
    }

    /// <summary>Unity host for the fixed complete-v1 demo fixture and its MessagePack snapshot.</summary>
    [DisallowMultipleComponent]
    public sealed class MapGeneratorDemoBehaviour : MonoBehaviour
    {
        private const string SnapshotExtension = ".msgpack";

        [FormerlySerializedAs("renderer")]
        [SerializeField] private MapSnapshotRenderer mapRenderer;
        [SerializeField] private string snapshotPath = "MapGeneratorDemo/map-v1-demo.msgpack";
        [SerializeField] private PixelMapProfile pixelProfile = PixelMapProfile.CreateDefault();
        [SerializeField] private List<DemoLocationTopologyDefinition> locationTopologies =
            new List<DemoLocationTopologyDefinition>
            {
                new DemoLocationTopologyDefinition
                {
                    groupName = "Roads",
                    topology = DemoLocationTopology.Linear,
                    nodeCount = 5
                },
                new DemoLocationTopologyDefinition
                {
                    groupName = "Lair",
                    topology = DemoLocationTopology.Branching,
                    nodeCount = 6,
                    maxDegree = 3
                },
                new DemoLocationTopologyDefinition
                {
                    groupName = "Settlement",
                    topology = DemoLocationTopology.Hub,
                    nodeCount = 7
                }
            };

        private readonly MapSnapshotSerializer serializer = new MapSnapshotSerializer();
        private MapSnapshot lastSnapshot;
        private int generationCount;

        public MapSnapshotRenderer Renderer
        {
            get
            {
                if (mapRenderer == null)
                    mapRenderer = GetComponent<MapSnapshotRenderer>() ?? gameObject.AddComponent<MapSnapshotRenderer>();
                return mapRenderer;
            }
            set => mapRenderer = value;
        }

        public string SnapshotPath
        {
            get => snapshotPath;
            set => snapshotPath = value;
        }

        public PixelMapProfile PixelProfile
        {
            get => pixelProfile;
            set => pixelProfile = value ?? throw new ArgumentNullException(nameof(value));
        }

        public List<DemoLocationTopologyDefinition> LocationTopologies => locationTopologies;

        public string ResolvedSnapshotPath => ResolveSnapshotPath();
        public MapSnapshot LastSnapshot => lastSnapshot;
        public int GenerationCount => generationCount;

        [ContextMenu("Generate And Save Sample")]
        /// <summary>
        /// Generates the sample map, saves its snapshot, and renders it.
        /// </summary>
        public void GenerateAndSaveSample()
        {
            var plot = CreatePlotFromTopologies();

            var snapshot = new MapGenerator().Generate(plot, PixelProfile.CreateOptions(Guid.NewGuid())).Snapshot;
            generationCount++;
            PersistAndRender(snapshot);
        }

        /// <summary>
        /// Generates the configured location topology groups for the demo plot.
        /// </summary>
        /// <returns>The plot containing all generated demo locations and passages.</returns>
        private Plot CreatePlotFromTopologies()
        {
            var plot = new Plot();
            var definitions = locationTopologies ?? new List<DemoLocationTopologyDefinition>();
            var random = new TopologyRandom(PixelProfile.Seed);

            for (var definitionIndex = 0; definitionIndex < definitions.Count; definitionIndex++)
            {
                var definition = definitions[definitionIndex];
                if (definition == null) continue;

                var root = new Element(ElemType.Location, definition.groupName);
                plot.Add(root);

                var request = CreateTopologyRequest(definition);
                var generator = new LocationTopologyGenerator(
                    request,
                    LocationStrategyRegistry.CreateDefault(),
                    random);
                var result = generator.Generate(plot, root, request);

                for (var locationIndex = 0; locationIndex < result.CreatedLocations.Count; locationIndex++)
                {
                    var location = result.CreatedLocations[locationIndex];
                    var groupName = string.IsNullOrWhiteSpace(definition.groupName)
                        ? $"Topology {definitionIndex + 1}"
                        : definition.groupName;
                    location.Name = $"{groupName} {locationIndex + 1:00}";
                }

                // The root is only an anchor required by LocationTopologyGenerator;
                // the map contains the generated locations themselves.
                plot.Remove(root);
            }

            return plot;
        }

        /// <summary>
        /// Creates a location-topology request from one serialized demo definition.
        /// </summary>
        /// <param name="definition">The serialized demo topology definition.</param>
        /// <returns>The corresponding location-topology request.</returns>
        /// <exception cref="ArgumentOutOfRangeException">Thrown when the configured topology value is unsupported.</exception>
        private static LocationTopologyRequest CreateTopologyRequest(
            DemoLocationTopologyDefinition definition)
        {
            var nodeCount = Mathf.Max(1, definition.nodeCount);
            return definition.topology switch
            {
                DemoLocationTopology.Linear => new LocationTopologyRequest(
                    "Linear", nodeCount, new LinearOptions(), LocationGenerationMode.Append),
                DemoLocationTopology.Branching => new LocationTopologyRequest(
                    "Branching", nodeCount,
                    new BranchingOptions(Mathf.Max(2, definition.maxDegree)),
                    LocationGenerationMode.Append),
                DemoLocationTopology.Loop => new LocationTopologyRequest(
                    "Loop", nodeCount,
                    new LoopOptions(Mathf.Max(1, definition.cycleCount),
                        Mathf.Max(2, definition.maxDegree)),
                    LocationGenerationMode.Append),
                DemoLocationTopology.Hub => new LocationTopologyRequest(
                    "Hub", nodeCount, new HubOptions(), LocationGenerationMode.Append),
                _ => throw new ArgumentOutOfRangeException()
            };
        }

        /// <summary>
        /// Adapts <see cref="System.Random"/> to the location-generator random contract.
        /// </summary>
        private sealed class TopologyRandom : ILocationRandom
        {
            private readonly System.Random random;

            /// <summary>
            /// Initializes a new deterministic random adapter with the supplied seed.
            /// </summary>
            /// <param name="seed">The deterministic seed.</param>
            public TopologyRandom(int seed)
            {
                random = new System.Random(seed);
            }

            /// <summary>
            /// Returns the next random integer below the specified upper bound.
            /// </summary>
            /// <param name="exclusiveMax">The exclusive upper bound.</param>
            /// <returns>The next random integer.</returns>
            public int Next(int exclusiveMax) => random.Next(exclusiveMax);
        }

        [ContextMenu("Load And Render")]
        /// <summary>
        /// Loads the saved map snapshot and renders it.
        /// </summary>
        public void LoadAndRender()
        {
            var payload = File.ReadAllBytes(ResolveSnapshotPath());
            var snapshot = serializer.Deserialize(payload);
            MapSnapshotValidator.Validate(snapshot);
            lastSnapshot = snapshot;
            Renderer.Render(snapshot);
            FrameMainCamera(snapshot);
        }

        /// <summary>
        /// Persists the snapshot and renders it in the scene.
        /// </summary>
        /// <param name="snapshot">The map snapshot to process.</param>
        private void PersistAndRender(MapSnapshot snapshot)
        {
            MapSnapshotValidator.Validate(snapshot);
            var outputPath = ResolveSnapshotPath();
            var directory = Path.GetDirectoryName(outputPath);
            if (!string.IsNullOrEmpty(directory)) Directory.CreateDirectory(directory);
            File.WriteAllBytes(outputPath, serializer.Serialize(snapshot));
            lastSnapshot = snapshot;
            Renderer.Render(snapshot);
            FrameMainCamera(snapshot);
        }

        /// <summary>
        /// Positions the main camera so the generated map is visible.
        /// </summary>
        /// <param name="snapshot">The map snapshot to process.</param>
        private void FrameMainCamera(MapSnapshot snapshot)
        {
            var camera = Camera.main;
            if (camera == null || !camera.orthographic) return;

            var cellSize = Renderer.CellSize;
            var width = snapshot.Dimensions.Width * cellSize;
            var height = snapshot.Dimensions.Height * cellSize;
            var position = camera.transform.position;
            camera.transform.position = new Vector3((width - cellSize) * 0.5f, position.y,
                (height - cellSize) * 0.5f);

            var aspect = Mathf.Max(camera.aspect, 0.0001f);
            camera.orthographicSize = Mathf.Max(height * 0.5f, width / (2f * aspect)) + cellSize;
        }

        /// <summary>
        /// Resolves the absolute path of the persisted map snapshot.
        /// </summary>
        /// <returns>The resulting string value.</returns>
        /// <exception cref="InvalidOperationException">Thrown when the operation cannot be completed in the current state.</exception>
        private string ResolveSnapshotPath()
        {
            if (string.IsNullOrWhiteSpace(snapshotPath))
                throw new InvalidOperationException("Snapshot path cannot be blank.");
            if (!string.Equals(Path.GetExtension(snapshotPath), SnapshotExtension, StringComparison.OrdinalIgnoreCase))
                throw new InvalidOperationException("Snapshot path must use the .msgpack extension.");
            if (Path.IsPathRooted(snapshotPath))
                throw new InvalidOperationException("Snapshot path must be relative to Unity persistent data.");

            var root = Path.GetFullPath(Application.persistentDataPath);
            var fullPath = Path.GetFullPath(Path.Combine(root, snapshotPath));
            var rootWithSeparator = root.EndsWith(Path.DirectorySeparatorChar.ToString(), StringComparison.Ordinal)
                ? root
                : root + Path.DirectorySeparatorChar;
            if (!fullPath.StartsWith(rootWithSeparator, StringComparison.Ordinal))
                throw new InvalidOperationException("Snapshot path must remain inside Unity persistent data.");
            return fullPath;
        }
    }
}
